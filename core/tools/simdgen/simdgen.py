# Data model
# =============================================================================

@dataclass
class TypeInfo:
    name: str
    vec_type: str
    scalar_type: str
    field_name: str
    lanes: int
    width: int
    mask_type: str
    ptr_type: str
    category: str
    decompose: Optional[list] = None


@dataclass
class Operation:
    name: str
    signature: str
    scalar_op: str
    doc: str
    applies_to: list
    scalar_body: Optional[any] = None
    scalar_vars: Optional[list] = None
    scalar_body_by_type: Optional[dict] = None
    scalar_vars_by_type: Optional[dict] = None
    mask_type_by_type: Optional[dict] = None
    name_pattern: Optional[str] = None
    facade_name_pattern: Optional[str] = None
    scalar_name_pattern: Optional[str] = None
    category: str = ""


@dataclass
class SlotEntry:
    """A single dispatch table slot = operation + type"""
    op: Operation
    type_info: Optional[TypeInfo]

    @property
    def base_name(self) -> str:
        type_name = self.type_info.name if self.type_info else ""
        if self.op.name_pattern:
            return self.op.name_pattern.format(op=self.op.name, type=type_name)
        if self.type_info is None:
            return self.op.name
        return f"{self.op.name}{self.type_info.name}"

    @property
    def dispatch_field(self) -> str:
        return self.base_name

    @property
    def facade_name(self) -> str:
        type_name = self.type_info.name if self.type_info else ""
        if self.op.facade_name_pattern:
            return self.op.facade_name_pattern.format(op=self.op.name, type=type_name)
        if self.type_info is None:
            return self.base_name
        if self.op.name_pattern:
            return self.base_name
        return f"Vec{self.type_info.name}{self.op.name}"

    @property
    def scalar_name(self) -> str:
        type_name = self.type_info.name if self.type_info else ""
        if self.op.scalar_name_pattern:
            return self.op.scalar_name_pattern.format(op=self.op.name, type=type_name, base=self.base_name)
        return f"Scalar{self.base_name}"


# =============================================================================
# Registry: load types and operations from JSON
# =============================================================================

class Registry:
    def __init__(self):
        self.types: dict[str, TypeInfo] = {}
        self.operations: list[Operation] = []
        self.slots: list[SlotEntry] = []

    def load_types(self, path: Path):
        with open(path) as f:
            data = json.load(f)
        for name, info in data.get("types", {}).items():
            if name.startswith("_") or name == "PLACEHOLDER_MORE_TYPES":
                continue
            self.types[name] = TypeInfo(
                name=name,
                vec_type=info["vec_type"],
                scalar_type=info["scalar_type"],
                field_name=info["field"],
                lanes=info["lanes"],
                width=info["width"],
                mask_type=info["mask"],
                ptr_type=info["ptr"],
                category=info["category"],
                decompose=info.get("decompose"),
            )

    def load_operations(self, path: Path):
        with open(path) as f:
            data = json.load(f)
        category = data.get("category", "")
        for op_def in data.get("operations", []):
            op = Operation(
                name=op_def["name"],
                signature=op_def["signature"],
                scalar_op=op_def.get("scalar_op", ""),
                doc=op_def.get("doc", ""),
                applies_to=op_def.get("applies_to", []),
                scalar_body=op_def.get("scalar_body"),
                scalar_vars=op_def.get("scalar_vars"),
                scalar_body_by_type=op_def.get("scalar_body_by_type"),
                scalar_vars_by_type=op_def.get("scalar_vars_by_type"),
                mask_type_by_type=op_def.get("mask_type_by_type"),
                name_pattern=op_def.get("name_pattern"),
                facade_name_pattern=op_def.get("facade_name_pattern"),
                scalar_name_pattern=op_def.get("scalar_name_pattern"),
                category=category,
            )
            self.operations.append(op)

    def build_slots(self):
        self.slots = []
        for op in self.operations:
            if op.signature in NO_TYPE_SIGNATURES and not op.applies_to:
                self.slots.append(SlotEntry(op=op, type_info=None))
                continue
            for type_name in op.applies_to:
                if type_name in self.types:
                    self.slots.append(SlotEntry(op=op, type_info=self.types[type_name]))

    def load_all(self):
        self.load_types(OPS_DIR / "types.json")
        for f in sorted(OPS_DIR.glob("*.json")):
            if f.name == "types.json":
                continue
            self.load_operations(f)
        self.build_slots()


