def canonical_sort_key(slot: SlotEntry) -> tuple[int, str, str]:
    """Keep generated include files stable and reviewable by vector family."""
    if slot.type_info is None:
        return (9999, slot.op.category, slot.base_name)
    return (slot.type_info.width, slot.type_info.name, slot.op.category)


def main() -> int:
    verify_mode = "--verify" in sys.argv
    dry_run = "--dry-run" in sys.argv
    # Current checked-in generated files use type-order. Keep --sort-by-type as
    # a compatibility spelling, but make the canonical default non-surprising.
    sort_by_type = True
    audit_mode = "--audit" in sys.argv
    category_filter = None
    for arg in sys.argv:
        if arg.startswith("--category="):
            category_filter = arg.split("=", 1)[1]

    registry = Registry()
    registry.load_all()

    if category_filter:
        registry.slots = [s for s in registry.slots if s.op.category == category_filter]

    if sort_by_type:
        registry.slots.sort(key=canonical_sort_key)

    print(f"[simdgen] Loaded {len(registry.types)} types, "
          f"{len(registry.operations)} operations, "
          f"{len(registry.slots)} slots")

    if audit_mode:
        run_audit(registry)
        return 0

    generators = {
        "nextpas.core.simd.dispatch.slots.inc": generate_dispatch_slots,
        "nextpas.core.simd.scalar.decl.inc": generate_scalar_decl,
        "nextpas.core.simd.scalar.impl.inc": generate_scalar_impl,
        "nextpas.core.simd.fillbase.inc": generate_fillbase,
        "nextpas.core.simd.facade.decl.inc": generate_facade_decl,
        "nextpas.core.simd.facade.impl.inc": generate_facade_impl,
    }

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    verify_failures = 0
    for filename, gen_func in generators.items():
        content = gen_func(registry)
        output_path = OUTPUT_DIR / filename

        if dry_run:
            print(f"\n{'='*60}")
            print(f"  {filename} ({len(content.splitlines())} lines)")
            print(f"{'='*60}")
            print(content[:2000])
            if len(content) > 2000:
                print(f"  ... ({len(content)} chars total)")
            continue

        if verify_mode:
            if output_path.exists():
                existing = output_path.read_text()
                if existing == content:
                    print(f"  [OK] {filename}")
                else:
                    print(f"  [DRIFT] {filename} - generated differs from existing")
                    verify_failures += 1
            else:
                print(f"  [NEW] {filename} - does not exist yet")
                verify_failures += 1
            continue

        output_path.write_text(content)
        print(f"  [WRITE] {filename} ({len(content.splitlines())} lines)")

    if verify_mode:
        # Also verify AVX2 batch kernels
        from simdgen_batch import verify_avx2_batch
        print("\n[simdgen] Verifying AVX2 batch kernels...")
        batch_rc = verify_avx2_batch()
        if batch_rc != 0:
            verify_failures += 1
        return 0 if verify_failures == 0 else 1

    if not dry_run and not verify_mode:
        print(f"\n[simdgen] Generated {len(generators)} files in {OUTPUT_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
