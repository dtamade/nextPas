def generate_scalar_impl(registry: Registry) -> str:
    lines = [HEADER, "{ Scalar implementation bodies }", "", "{$PUSH}{$Q-}{$R-}", ""]
    for slot in registry.slots:
        t = slot.type_info
        sig = slot.op.signature
        op = slot.op

        if sig == "binary":
            lines.append(f"function {slot.scalar_name}(const a, b: {t.vec_type}): {t.vec_type};")
            type_lines = render_type_lines(typed_template(op.scalar_body_by_type, t), t)
            scalar_vars = render_type_lines(typed_template(op.scalar_vars_by_type, t), t)
            append_scalar_var_block(lines, scalar_vars, include_i=not type_lines or code_uses_identifier(type_lines, "i"))
            lines.append("begin")
            if type_lines:
                for body_line in type_lines:
                    lines.append(f"  {body_line}" if body_line else "")
            elif op.scalar_body:
                body = op.scalar_body.replace("{field}", t.field_name)
                lines.append(f"  for i := 0 to {t.lanes - 1} do")
                lines.append(f"    {body};")
            elif op.scalar_op in ("+", "-", "*", "/", "and", "or", "xor"):
                lines.append(f"  for i := 0 to {t.lanes - 1} do")
                lines.append(
                    f"    Result.{t.field_name}[i] := a.{t.field_name}[i] "
                    f"{op.scalar_op} b.{t.field_name}[i];"
                )
            else:
                lines.append(f"  // TODO: implement scalar {op.name} for {t.name}")
                lines.append(f"  Result := a;")
            lines.append("end;")
            lines.append("")

        elif sig == "unary":
            lines.append(f"function {slot.scalar_name}(const a: {t.vec_type}): {t.vec_type};")
            type_lines = render_type_lines(typed_template(op.scalar_body_by_type, t), t)
            scalar_vars = render_type_lines(typed_template(op.scalar_vars_by_type, t), t)
            append_scalar_var_block(lines, scalar_vars, include_i=not type_lines or code_uses_identifier(type_lines, "i"))
            lines.append("begin")
            if type_lines:
                for body_line in type_lines:
                    lines.append(f"  {body_line}" if body_line else "")
            elif op.scalar_body:
                body = op.scalar_body.replace("{field}", t.field_name)
                lines.append(f"  for i := 0 to {t.lanes - 1} do")
                lines.append(f"    {body};")
            elif op.scalar_op == "not":
                lines.append(f"  for i := 0 to {t.lanes - 1} do")
                lines.append(f"    Result.{t.field_name}[i] := not a.{t.field_name}[i];")
            else:
                lines.append(f"  // TODO: implement scalar {op.name} for {t.name}")
                lines.append(f"  Result := a;")
            lines.append("end;")
            lines.append("")

        elif sig == "shift":
            lines.append(f"function {slot.scalar_name}(const a: {t.vec_type}; count: Integer): {t.vec_type};")
            type_lines = render_type_lines(typed_template(op.scalar_body_by_type, t), t)
            scalar_vars = render_type_lines(typed_template(op.scalar_vars_by_type, t), t)
            # If scalar_body is a list, treat it as multi-line body (like type_lines)
            fallback_lines: list[str] = []
            if not type_lines and op.scalar_body and isinstance(op.scalar_body, list):
                fallback_lines = render_type_lines(op.scalar_body, t)
            append_scalar_var_block(lines, scalar_vars, include_i=not (type_lines or fallback_lines) or
                code_uses_identifier(type_lines or fallback_lines, "i"))
            lines.append("begin")
            if type_lines:
                for body_line in type_lines:
                    lines.append(f"  {body_line}" if body_line else "")
            elif fallback_lines:
                for body_line in fallback_lines:
                    lines.append(f"  {body_line}" if body_line else "")
            elif op.scalar_body and isinstance(op.scalar_body, str):
                body = op.scalar_body.replace("{field}", t.field_name)
                lines.append(f"  for i := 0 to {t.lanes - 1} do")
                lines.append(f"    {body};")
            elif op.scalar_op in ("shl", "shr"):
                lines.append(f"  for i := 0 to {t.lanes - 1} do")
                lines.append(f"    Result.{t.field_name}[i] := a.{t.field_name}[i] {op.scalar_op} count;")
            else:
                lines.append(f"  // TODO: implement scalar {op.name} for {t.name}")
                lines.append(f"  Result := a;")
            lines.append("end;")
            lines.append("")

        elif sig == "compare":
            lines.append(f"function {slot.scalar_name}(const a, b: {t.vec_type}): {t.mask_type};")
            lines.append("var i: Integer;")
            lines.append("begin")
            lines.append(f"  Result := 0;")
            lines.append(f"  for i := 0 to {t.lanes - 1} do")
            lines.append(f"    if a.{t.field_name}[i] {op.scalar_op} b.{t.field_name}[i] then")
            lines.append(f"      Result := Result or ({t.mask_type}(1) shl i);")
            lines.append("end;")
            lines.append("")

        elif sig == "reduce":
            lines.append(f"function {slot.scalar_name}(const a: {t.vec_type}): {t.scalar_type};")
            type_lines = render_type_lines(typed_template(op.scalar_body_by_type, t), t)
            scalar_vars = render_type_lines(typed_template(op.scalar_vars_by_type, t), t)
            append_scalar_var_block(lines, scalar_vars, include_i=not type_lines or code_uses_identifier(type_lines, "i"))
            lines.append("begin")
            if type_lines:
                for body_line in type_lines:
                    lines.append(f"  {body_line}" if body_line else "")
            elif "Add" in op.name:
                lines.append(f"  Result := a.{t.field_name}[0];")
                lines.append(f"  for i := 1 to {t.lanes - 1} do")
                lines.append(f"    Result := Result + a.{t.field_name}[i];")
            elif "Min" in op.name:
                lines.append(f"  Result := a.{t.field_name}[0];")
                lines.append(f"  for i := 1 to {t.lanes - 1} do")
                lines.append(f"    if a.{t.field_name}[i] < Result then Result := a.{t.field_name}[i];")
            elif "Max" in op.name:
                lines.append(f"  Result := a.{t.field_name}[0];")
                lines.append(f"  for i := 1 to {t.lanes - 1} do")
                lines.append(f"    if a.{t.field_name}[i] > Result then Result := a.{t.field_name}[i];")
            elif "Mul" in op.name:
                lines.append(f"  Result := a.{t.field_name}[0];")
                lines.append(f"  for i := 1 to {t.lanes - 1} do")
                lines.append(f"    Result := Result * a.{t.field_name}[i];")
            else:
                lines.append(f"  // TODO: implement scalar {op.name} for {t.name}")
                lines.append(f"  Result := 0;")
            lines.append("end;")
            lines.append("")

        elif sig == "load":
            lines.append(f"function {slot.scalar_name}(p: {t.ptr_type}): {t.vec_type};")
            if op.scalar_op == "custom":
                body_lines = render_type_lines(typed_template(op.scalar_body_by_type, t), t)
                if not body_lines:
                    body_lines = render_type_lines(op.scalar_body, None)
                if not body_lines:
                    raise ValueError(f"Custom load op {slot.dispatch_field} missing scalar body")
                scalar_vars = render_type_lines(typed_template(op.scalar_vars_by_type, t), t)
                append_scalar_var_block(lines, scalar_vars, include_i=code_uses_identifier(body_lines, "i"))
                lines.append("begin")
                for body_line in body_lines:
                    lines.append(f"  {body_line}" if body_line else "")
                lines.append("end;")
            else:
                lines.append("var i: Integer;")
                lines.append("begin")
                lines.append(f"  Assert(p <> nil, '{slot.scalar_name}: pointer is nil');")
                lines.append(f"  for i := 0 to {t.lanes - 1} do")
                lines.append(f"    Result.{t.field_name}[i] := p[i];")
                lines.append("end;")
            lines.append("")

        elif sig == "store":
            lines.append(f"procedure {slot.scalar_name}(p: {t.ptr_type}; const a: {t.vec_type});")
            if op.scalar_op == "custom":
                body_lines = render_type_lines(typed_template(op.scalar_body_by_type, t), t)
                if not body_lines:
                    body_lines = render_type_lines(op.scalar_body, None)
