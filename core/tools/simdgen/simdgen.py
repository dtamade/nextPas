def render_type_lines(value, type_info: Optional[TypeInfo]) -> list[str]:
    """Render optional JSON code templates for a specific vector type."""
    if value is None:
        return []
    if isinstance(value, list):
        raw_lines = value
    else:
        raw_lines = str(value).splitlines()
    rendered_lines = []
    for line in raw_lines:
        if type_info is not None:
            lane_bits = type_info.width // type_info.lanes if type_info.lanes > 0 else 0
            line = (
                line
                .replace("{field}", type_info.field_name)
                .replace("{type}", type_info.name)
                .replace("{scalar_type}", type_info.scalar_type)
                .replace("{lanes}", str(type_info.lanes))
                .replace("{lane_bits}", str(lane_bits))
            )
        else:
            line = (
                line
                .replace("{field}", "")
                .replace("{type}", "")
                .replace("{scalar_type}", "")
                .replace("{lanes}", "0")
                .replace("{lane_bits}", "0")
            )
        rendered_lines.append(line)
    return rendered_lines


def typed_template(mapping: Optional[dict], type_info: TypeInfo):
    """Return a per-type template from an operation definition, if present."""
    if not mapping:
        return None
    return mapping.get(type_info.name)


def code_uses_identifier(lines: list[str], identifier: str) -> bool:
    """Return true when rendered Pascal template lines reference an identifier."""
    pattern = re.compile(rf"\b{re.escape(identifier)}\b")
    return any(pattern.search(line) for line in lines)


def append_scalar_var_block(lines: list[str], scalar_vars: list[str], include_i: bool) -> None:
    """Append a Pascal var block, omitting unused generated loop indexes."""
    if not include_i and not scalar_vars:
        return
    if include_i and not scalar_vars:
        lines.append("var i: Integer;")
        return
    lines.append("var")
    if include_i:
        lines.append("  i: Integer;")
    for scalar_var in scalar_vars:
        lines.append(f"  {scalar_var.rstrip(';')};")


def select_mask_type(slot: SlotEntry) -> str:
    """Return the mask parameter type for Select-like slots."""
    mapping = slot.op.mask_type_by_type or {}
    return mapping.get(slot.type_info.name, slot.type_info.mask_type)


def pointer_ptr_len_result_type(signature: str) -> str:
    """Return the Pascal result type for pointer-pointer-length helper slots."""
    return POINTER_PTR_LEN_RESULT_TYPES[signature]


def pointer_len_result_type(signature: str) -> str:
    """Return the Pascal result type for pointer-length helper slots."""
    return POINTER_LEN_RESULT_TYPES[signature]


def pointer_len_byte_result_type(signature: str) -> str:
    """Return the Pascal result type for pointer-length-byte helper slots."""
    return POINTER_LEN_BYTE_RESULT_TYPES[signature]


def pointer_ptr_len_out_result_type(signature: str) -> str:
    """Return the Pascal result type for pointer-pointer-length helpers with out params."""
    return POINTER_PTR_LEN_OUT_RESULT_TYPES[signature]


def pointer_len_ptr_len_result_type(signature: str) -> str:
    """Return the Pascal result type for pointer-length/pointer-length helper slots."""
    return POINTER_LEN_PTR_LEN_RESULT_TYPES[signature]


def gen_signature(slot: SlotEntry) -> str:
    """Generate the function pointer type signature for a dispatch slot."""
    t = slot.type_info
    sig = slot.op.signature

    if sig == "binary":
        return f"function(const a, b: {t.vec_type}): {t.vec_type}"
    elif sig == "unary":
        return f"function(const a: {t.vec_type}): {t.vec_type}"
    elif sig == "compare":
        return f"function(const a, b: {t.vec_type}): {t.mask_type}"
    elif sig == "reduce":
        return f"function(const a: {t.vec_type}): {t.scalar_type}"
    elif sig == "reduce_binary":
        return f"function(const a, b: {t.vec_type}): {t.scalar_type}"
    elif sig == "load":
        return f"function(p: {t.ptr_type}): {t.vec_type}"
    elif sig == "store":
        return f"procedure(p: {t.ptr_type}; const a: {t.vec_type})"
    elif sig == "splat":
        return f"function(value: {t.scalar_type}): {t.vec_type}"
    elif sig == "zero":
        return f"function: {t.vec_type}"
    elif sig == "shift":
        return f"function(const a: {t.vec_type}; count: Integer): {t.vec_type}"
    elif sig == "ternary":
        return f"function(const a, b, c: {t.vec_type}): {t.vec_type}"
    elif sig == "select":
        return f"function(const mask: {select_mask_type(slot)}; const a, b: {t.vec_type}): {t.vec_type}"
    elif sig == "extract":
        return f"function(const a: {t.vec_type}; index: Integer): {t.scalar_type}"
    elif sig == "insert":
        return f"function(const a: {t.vec_type}; value: {t.scalar_type}; index: Integer): {t.vec_type}"
    elif sig == "mask_bool":
        return f"function(mask: {t.mask_type}): Boolean"
    elif sig == "mask_int":
        return f"function(mask: {t.mask_type}): Integer"
    elif sig in POINTER_LEN_RESULT_TYPES:
        return f"function(p: Pointer; len: SizeUInt): {pointer_len_result_type(sig)}"
    elif sig in POINTER_LEN_BYTE_RESULT_TYPES:
        return f"function(p: Pointer; len: SizeUInt; value: Byte): {pointer_len_byte_result_type(sig)}"
    elif sig in POINTER_PTR_LEN_RESULT_TYPES:
        return f"function(a, b: Pointer; len: SizeUInt): {pointer_ptr_len_result_type(sig)}"
    elif sig in POINTER_PTR_LEN_OUT_RESULT_TYPES:
        return f"function(a, b: Pointer; len: SizeUInt; out firstDiff, lastDiff: SizeUInt): {pointer_ptr_len_out_result_type(sig)}"
    elif sig in POINTER_LEN_PTR_LEN_RESULT_TYPES:
        return f"function(haystack: Pointer; haystackLen: SizeUInt; needle: Pointer; needleLen: SizeUInt): {pointer_len_ptr_len_result_type(sig)}"
    elif sig in POINTER_LEN_VOID_SIGNATURES:
        return "procedure(p: Pointer; len: SizeUInt)"
    elif sig in POINTER_LEN_BYTE_VOID_SIGNATURES:
        return "procedure(dst: Pointer; len: SizeUInt; value: Byte)"
    elif sig in POINTER_LEN_OUT_BYTE_VOID_SIGNATURES:
        return "procedure(p: Pointer; len: SizeUInt; out minVal, maxVal: Byte)"
    elif sig in POINTER_PTR_LEN_VOID_SIGNATURES:
        return "procedure(src, dst: Pointer; len: SizeUInt)"
    elif sig == "psingle_count_single":
        return "function(aSrc: PSingle; aCount: SizeUInt): Single"
    elif sig == "psingle_psingle_count_single":
        return "function(aSrc1, aSrc2: PSingle; aCount: SizeUInt): Single"
    elif sig == "psingle_psingle_psingle_count_void":
        return "procedure(aSrc1, aSrc2, aDst: PSingle; aCount: SizeUInt)"
    elif sig == "psingle_psingle_count_single_void":
        return "procedure(aSrc, aDst: PSingle; aCount: SizeUInt; aScalar: Single)"
    elif sig == "single_psingle_psingle_psingle_count_void":
        return "procedure(aAlpha: Single; aX, aY, aDst: PSingle; aCount: SizeUInt)"
    else:
        return f"{{unknown signature: {sig}}}"


def generate_dispatch_slots(registry: Registry) -> str:
    lines = [HEADER, "{ Dispatch table slots }", ""]
    current_category = ""
    for slot in registry.slots:
        if slot.op.category != current_category:
            current_category = slot.op.category
            lines.append(f"    {{ --- {current_category} --- }}")
        sig = gen_signature(slot)
        lines.append(f"    {slot.dispatch_field}: {sig};")
    return "\n".join(lines) + "\n"


