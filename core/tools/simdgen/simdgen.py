            scalar_vars = render_type_lines(op.scalar_vars, None)
            body_lines = render_type_lines(op.scalar_body, None)
            append_scalar_var_block(lines, scalar_vars, include_i=False)
            lines.append("begin")
            for body_line in body_lines:
                lines.append(f"  {body_line}" if body_line else "")
            lines.append("end;")
